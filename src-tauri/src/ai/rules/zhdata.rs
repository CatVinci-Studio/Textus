/// Every pair, Simplified first.
pub(crate) fn script_pairs() -> impl Iterator<Item = &'static (char, char, Pair)> {
    BOTH.iter()
        .filter(|(s, t, _)| s != t)
        .chain(SIMP_ONLY)
        .chain(TRAD_ONLY)
}

/// The Simplified form of a Traditional-only character.
pub(crate) fn to_simplified(c: char) -> Option<char> {
    script_pairs()
        .find(|(_, t, kind)| *t == c && *kind != Pair::SimpOnly)
        .map(|(s, _, _)| *s)
}

/// The Traditional form(s) of a Simplified-only character.
pub(crate) fn to_traditional(c: char) -> Option<Vec<char>> {
    let forms: Vec<char> = script_pairs()
        .filter(|(s, _, kind)| *s == c && *kind != Pair::TradOnly)
        .map(|(_, t, _)| *t)
        .chain(
            // The other readings of a one-to-many character.
            script_pairs()
                .filter(|(s, _, kind)| *s == c && *kind == Pair::TradOnly)
                .filter(|_| script_pairs().any(|(s2, _, k2)| *s2 == c && *k2 == Pair::SimpOnly))
                .map(|(_, t, _)| *t),
        )
        .collect();
    (!forms.is_empty()).then_some(forms)
}


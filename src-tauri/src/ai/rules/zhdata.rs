//! Word and character lists for the Chinese rules: our own small,
//! high-precision lists of the common unambiguous pairs, rather than OpenCC's
//! large dictionaries.

/// How a Simplified/Traditional pair converts.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Pair {
    /// One-to-one both ways.
    Both,
    /// The Simplified character exists only in Simplified text, but stands
    /// for several Traditional ones (发 -> 發/髮): flagged in Traditional
    /// text without a single suggestion.
    SimpOnly,
    /// The Traditional character exists only in Traditional text, but its
    /// Simplified form is also a Traditional character (後 -> 后, 裡 -> 里):
    /// flagged in Simplified text only.
    TradOnly,
}

macro_rules! pairs {
    ($kind:ident: $($s:literal $t:literal)*) => {
        &[$(($s, $t, Pair::$kind)),*]
    };
}


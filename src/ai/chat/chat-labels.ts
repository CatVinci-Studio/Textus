/** Each mode's name and line, as the composer's picker shows them. */
function modeLabels(t: Strings) {
  const of = (mode: PanelMode) => ({
    label: t[MODES[mode].label],
    hint: t[MODES[mode].hint],
  });
  return {
    write: of("write"),
    review: of("review"),
    create: of("create"),
    research: of("research"),
  };
}

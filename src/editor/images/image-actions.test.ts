import { expect, it, vi } from "vitest";
vi.mock("../../platform/ipc", () => ({ media: {}, fs: {} }));
import { isGeneratedImage } from "./image-actions";

it("recognises images Textus generated by their stored name, wherever they moved", () => {
  expect(isGeneratedImage("assets/image-1792327718948718000-24521-0.jpg")).toBe(
    true,
  );
  expect(
    isGeneratedImage(
      "/Users/me/Library/Application%20Support/com.catvinci.textus/assets/image-1-2-0.png",
    ),
  ).toBe(true);
  expect(isGeneratedImage("assets/20261018-120000-ab12.png")).toBe(false);
  expect(isGeneratedImage("https://example.com/image-1-2-0.jpg?x=1")).toBe(
    true,
  );
  expect(isGeneratedImage("assets/photo.png")).toBe(false);
  // Renamed by a Save As name collision.
  expect(isGeneratedImage("assets/image-1-2-0-1.jpg")).toBe(true);
});
